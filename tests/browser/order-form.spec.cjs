const {test, expect} = require('@playwright/test');

test('order sections preserve hidden recorded values and reveal save failures', async ({page}, testInfo) => {
  await page.goto('/?demo=1');
  const before = await page.evaluate(() => {
    const order = DB.orders.o_3;
    order.workflow = buildDefaultWorkflow(order.date, order.status, order.assignedTo, order.karigarAssigned);
    order.workflow[7] = {...order.workflow[7], done:true, doneDate:'2026-11-01', notes:'Retain completed history'};
    order.fabricMeters = 0;
    order.hoursSpent = null;
    order.assignedTo = 'Former cutter';
    order.karigarAssigned = 'Former stitcher';
    order.customLegacyField = 'retain unknown data';
    localStorage.setItem(DB_KEY, JSON.stringify(DB));
    return JSON.parse(JSON.stringify(order));
  });
  await page.locator('[data-v="orders"]').click();
  await page.locator('[data-open-tracked-order="o_3"]').click();
  const opener = page.locator('[data-act="editOrder"][data-id="o_3"]');
  await opener.click();
  await expect(page.getByLabel('Client', {exact:true})).toBeVisible();
  await expect(page.locator('#omAmount')).toBeHidden();
  await expect(page.locator('#omAssigned')).toBeHidden();
  await expect(page.locator('#omMeters')).toBeHidden();
  await expect(page.locator('#omSave')).toBeInViewport();
  await page.screenshot({path:testInfo.outputPath('order-form-default.png')});
  const summary = page.locator('#omNotesSection > summary');
  await summary.focus();await page.keyboard.press('Enter');
  await page.getByLabel('Order & Trial Notes', {exact:true}).fill('Changed instructions only');
  await summary.click();
  await page.locator('#omFabricSummary').click();
  await expect(page.getByLabel('Cloth Required (Meters)', {exact:true})).toHaveValue('0');
  await page.locator('#omFabricSummary').click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem(DB_KEY)).orders.o_3)).toEqual(before);
  await page.evaluate(() => { window.originalOrderWriter = writeDatabase; writeDatabase = async () => {throw new Error('Synthetic storage failure');}; });
  await page.locator('#omSave').click();
  await expect(page.locator('#omSaveError')).toContainText('Synthetic storage failure');
  await expect(page.locator('#omSaveError')).toBeInViewport();
  await expect(page.locator('#omNotes')).toHaveValue('Changed instructions only');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem(DB_KEY)).orders.o_3)).toEqual(before);
  await page.evaluate(() => {writeDatabase = window.originalOrderWriter;});
  await page.locator('#omSave').click();
  await expect(page.locator('#overlay')).toBeHidden();
  await expect(opener).toBeFocused();
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem(DB_KEY)).orders.o_3);
  expect(after.notes).toBe('Changed instructions only');
  for (const field of ['fabricMeters','fabricRate','trimsCost','cutterCost','karigarCost','trialShippingCost','amount','advancePaid','hoursSpent','assignedTo','karigarAssigned','workflow','customLegacyField']) expect(after[field], field).toEqual(before[field]);
  await page.reload();
  expect(await page.evaluate(() => DB.orders.o_3.notes)).toBe('Changed instructions only');
  expect(await page.evaluate(() => localStorage.getItem('modisto_bespoke_v7'))).toBeNull();
});

test('cost review opens directly, supports keyboard closing and remains usable with enlarged text', async ({page}, testInfo) => {
  await page.goto('/?demo=1');
  await page.locator('[data-v="orders"]').click();
  await page.locator('[data-open-tracked-order="o_3"]').click();
  await page.locator('[data-order-section="costs"]').click();
  const opener = page.locator('[data-act="reviewOrderCosts"]');
  const before = await page.evaluate(() => localStorage.getItem(DB_KEY));
  await opener.click();
  await expect(page.locator('#omCostsSummary')).toBeFocused();
  await expect(page.getByLabel('Recorded received total (₹)', {exact:true})).toBeVisible();
  await expect(page.locator('#omRate')).toBeHidden();
  await page.locator('#omCostBreakdown > summary').click();
  await expect(page.getByLabel('Cloth Cost / Meter (₹)', {exact:true})).toBeVisible();
  await page.addStyleTag({content:'.order-form :is(label, input, select, textarea, button, summary, p, small, span) {font-size: 24px !important;}'});
  expect(await page.locator('#modal').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.locator('#omSave').scrollIntoViewIfNeeded();
  await expect(page.locator('#omSave')).toBeInViewport();
  await page.screenshot({path:testInfo.outputPath('order-form-costs-large-text.png')});
  await page.keyboard.press('Escape');
  await expect(page.locator('#overlay')).toBeHidden();
  await expect(opener).toBeFocused();
  expect(await page.evaluate(() => localStorage.getItem(DB_KEY))).toBe(before);
});
