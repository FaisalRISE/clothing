test('legacy records, extra fitting history and nonsequential completion survive save and reload', async ({page}) => {
  await page.goto('/');
  const legacy = await page.evaluate(()=>{
    const data=getSeedData();
    data.orders.o_3.workflow=buildDefaultWorkflow('2026-10-01','New','Committed cutter','Committed maker');
    data.orders.o_3.workflow[7]={...data.orders.o_3.workflow[7],done:true,doneDate:'2026-10-31',daysTaken:0,notes:'Existing completed task'};
    data.orders.o_3.workflow.push({key:'trial_3',stage:'1st Trial / Fitting',label:'Third fitting',done:true,doneDate:'2026-10-29',daysTaken:1,assignedTo:'Legacy maker',notes:'Retain extra fitting'});
    const raw=JSON.stringify(data);
    localStorage.setItem('modisto_bespoke_v6',raw);
    return raw;
  });
  await page.reload();
  const before=await page.evaluate(()=>JSON.stringify(DB.orders.o_3));
  await page.evaluate(()=>ACTIONS.openSequenceModal('o_3'));
  await expect(page.locator('.seq-chk')).toHaveCount(10);
  await page.locator('#seqClose').click();
  expect(await page.evaluate(()=>JSON.stringify(DB.orders.o_3))).toBe(before);
  await page.evaluate(()=>ACTIONS.openMeasureByOrder('o_3'));
  await page.locator('[data-m="Inseam"]').fill('29.75');
  await page.locator('#abSave').click();
  await page.reload();
  expect(await page.evaluate(()=>JSON.stringify(DB.orders.o_3))).toBe(before);
  expect(await page.evaluate(()=>localStorage.getItem('modisto_bespoke_v6'))).toBe(legacy);
  await page.evaluate(()=>ACTIONS.openSequenceModal('o_3'));
  await page.locator('.seq-chk[data-idx="3"]').check();
  const state=await page.evaluate(()=>DB.orders.o_3.workflow);
  expect(state[0].done).toBe(false);
  expect(state[3].done).toBe(true);
  expect(state[3].daysTaken).toBe('');
  expect(state[7].doneDate).toBe('2026-10-31');
  expect(state[9].assignedTo).toBe('Legacy maker');
  await page.locator('#seqClose').click();
});

test('new workspace stays empty; corrupt storage remains downloadable and recoverable', async ({page}) => {
  await page.goto('/');
  expect(await page.evaluate(()=>Object.keys(DB.clients).length)).toBe(0);
  await page.evaluate(()=>localStorage.setItem('modisto_bespoke_v7','broken original JSON'));
  await page.reload();
  await expect(page.locator('.mode-banner')).toContainText('Saving is blocked');
  await navigate(page, 'settings');
  const downloading=page.waitForEvent('download');
  await page.locator('[data-act="exportRecovery"]').click();
  const download=await downloading;
  const stream=await download.createReadStream();
  const chunks=[];for await(const chunk of stream)chunks.push(chunk);
  expect(Buffer.concat(chunks).toString()).toBe('broken original JSON');
  await page.locator('[data-act="importDb"]').click();
  const restored={clients:{c:{id:'c',name:'Recovered patron'}},orders:{},measurements:{},swatches:{},employees:{},settings:{}};
  await page.locator('#importFile').setInputFiles({name:'recovery.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(restored))});
  await expect(page.locator('.mode-banner')).toHaveCount(0);
  expect(await page.evaluate(()=>DB.clients.c.name)).toBe('Recovered patron');
  expect(await page.evaluate(()=>localStorage.getItem('modisto_bespoke_v7_recovery'))).toBe('broken original JSON');
  await page.reload();
  expect(await page.evaluate(()=>Object.keys(DB.orders).length)).toBe(0);
});

test('new orders and enquiries have no invented business values or completion history', async ({page}) => {
  await page.goto('/?demo=1');
  await page.evaluate(()=>ACTIONS.newOrderPick());
  for(const id of ['omAmount','omAdvance','omTrims','omCutter','omKarigarCost','omShip','omHours','omActDays','omRate','omMeters','omEstDays','omEstHours']) {
    await expect(page.locator('#'+id)).toHaveValue('');
  }
  await page.locator('#omSave').click();
  const created = await page.evaluate(()=>Object.values(DB.orders).find(o=>o.id.startsWith('o_') && !['o_1','o_2','o_3','o_4'].includes(o.id)));
  expect(created.amount).toBeNull(); expect(created.advancePaid).toBeNull();
  expect(created.workflow.every(s=>!s.done&&!s.doneDate)).toBe(true);
  await page.evaluate(()=>ACTIONS.openEnquiryWizard());
  await page.locator('#eqProceed').click();
  const order=await page.evaluate(()=>Object.values(DB.orders).find(o=>o.orderNo===MREC.orderNo));
  expect(order.amount).toBeNull(); expect(order.advancePaid).toBeNull();
  expect(order.fabricMeters).toBeNull(); expect(order.hoursSpent).toBeNull();
  expect(order.trialDate).toBe(''); expect(order.delivery).toBe('');
  expect(order.workflow.every(s=>!s.done&&!s.doneDate)).toBe(true);
});

